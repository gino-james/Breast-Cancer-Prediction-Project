import streamlit as st
import joblib
import numpy as np

# Load the trained model and scaler
model = joblib.load("breast_cancer_model.pkl")
scaler = joblib.load("scaler.pkl")

st.title("🔬 Breast Cancer Prediction App")

st.write("Enter tumor feature values to predict whether it's **Malignant or Benign**")

# Input fields (use same features as training dataset)
mean_radius = st.number_input("Mean Radius")
mean_texture = st.number_input("Mean Texture")
mean_perimeter = st.number_input("Mean Perimeter")
mean_area = st.number_input("Mean Area")
mean_smoothness = st.number_input("Mean Smoothness")

# You can add more inputs according to dataset features

if st.button("Predict"):
    input_data = np.array([[mean_radius, mean_texture, mean_perimeter, mean_area, mean_smoothness]])
    input_data_scaled = scaler.transform(input_data)
    prediction = model.predict(input_data_scaled)[0]

    if prediction == 1:  # Assuming 1 = Malignant
        st.error("🚨 Prediction: Malignant (Cancerous)")
    else:
        st.success("✅ Prediction: Benign (Non-Cancerous)")