import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

#importing the dataset
df = pd.read_csv('Breast_cancer_dataset.csv')
df.head()

print(df.info())
print(df.head())
print(df.describe())

"""Data Preprocessing"""

# dropping unnecessary columns
df.drop(['Unnamed: 32','id'],axis=1,inplace=True)

#checking for the missing values
df.isnull().sum()

df.dtypes

df.describe()

"""Exploratory Data Analysis"""

# Class distribution
print(df["diagnosis"].value_counts())
sns.countplot(x='diagnosis', data=df)
plt.title("Diagnosis Distribution")
plt.show()

# Pairplot for first few columns to see basic trends
sns.pairplot(df.iloc[:, 1:6].join(df["diagnosis"]), hue="diagnosis")
plt.show()

# Correlation matrix and heatmap
corr = df.drop('diagnosis', axis=1).corr()
plt.figure(figsize=(16,10))
sns.heatmap(corr, cmap='coolwarm', annot=False)
plt.title("Correlation Heatmap")
plt.show()

# Distribution plots for major features
features = df.columns.drop('diagnosis')
for feature in features:
    plt.figure(figsize=(6,4))
    sns.histplot(df[feature], kde=True)
    plt.title(f"Distribution of {feature}")
    plt.show()

"""Train Test Split"""

from sklearn.model_selection import train_test_split
X_train,X_test,y_train,y_test = train_test_split(df.drop(['diagnosis'],axis=1),df['diagnosis'],test_size=0.3,random_state=42)

from sklearn.preprocessing import LabelEncoder, StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import classification_report, accuracy_score, confusion_matrix, roc_curve, roc_auc_score

# 1. Label Encoding
le = LabelEncoder()
y_train_enc = le.fit_transform(y_train)
y_test_enc = le.transform(y_test)

# 2. Feature Scaling
scaler = StandardScaler()
X_train_scaled = scaler.fit_transform(X_train)
X_test_scaled = scaler.transform(X_test)

# 3. Model Training
clf = LogisticRegression(random_state=42)
clf.fit(X_train_scaled, y_train_enc)

# 4. Prediction
y_pred = clf.predict(X_test_scaled)

# 5. Evaluation
print("Accuracy:", accuracy_score(y_test_enc, y_pred))
print("Classification Report:\n", classification_report(y_test_enc, y_pred))
print("Confusion Matrix:\n", confusion_matrix(y_test_enc, y_pred))

"""Feature Importance with Logistic Regression"""

# Assuming clf is your trained LogisticRegression model
feature_names = X_train.columns
feature_importance = np.abs(clf.coef_[0])
importances_df = pd.DataFrame({'feature': feature_names, 'importance': feature_importance})
importances_df = importances_df.sort_values('importance', ascending=False)
print(importances_df)

# Visualize top features
import matplotlib.pyplot as plt
plt.figure(figsize=(10,6))
plt.barh(importances_df['feature'][:10], importances_df['importance'][:10])
plt.xlabel('Importance')
plt.ylabel('Feature')
plt.title('Top 10 Important Features')
plt.gca().invert_yaxis()
plt.show()



"""Try More Models and Hyperparameter Tuning"""

from sklearn.ensemble import RandomForestClassifier
from sklearn.model_selection import GridSearchCV

# Try a Random Forest with basic grid search
param_grid = {'n_estimators': [50, 100, 200], 'max_depth': [3, 5, 7, None]}
rf = RandomForestClassifier(random_state=42)
grid_search = GridSearchCV(rf, param_grid, cv=5)
grid_search.fit(X_train_scaled, y_train_enc)
print("Best parameters:", grid_search.best_params_)
print("Best RF accuracy:", grid_search.score(X_test_scaled, y_test_enc))

""" Visualize Confusion Matrix"""

cm = confusion_matrix(y_test_enc, y_pred)
sns.heatmap(cm, annot=True, fmt='d', cmap='Blues')
plt.xlabel('Predicted')
plt.ylabel('Actual')
plt.title('Confusion Matrix')
plt.show()

"""ROC Curve and AUC"""

# Predict probabilities for positive class
from sklearn.metrics import roc_curve, roc_auc_score
y_probs = clf.predict_proba(X_test_scaled)[:, 1]

# Compute ROC curve and AUC
fpr, tpr, thresholds = roc_curve(y_test_enc, y_probs)
auc_score = roc_auc_score(y_test_enc, y_probs)

# Plot ROC curve
plt.figure()
plt.plot(fpr, tpr, label=f'ROC curve (AUC = {auc_score:.2f})')
plt.plot([0, 1], [0, 1], 'k--')  # random chance line
plt.xlabel('False Positive Rate')
plt.ylabel('True Positive Rate')
plt.title('Receiver Operating Characteristic (ROC)')
plt.legend(loc='lower right')
plt.show()

"""
Cross-Validation"""

from sklearn.model_selection import cross_val_score
cv_scores = cross_val_score(clf, scaler.transform(df.drop(['diagnosis'], axis=1)),
                            le.fit_transform(df['diagnosis']), cv=5)
print("Cross-Validation Scores:", cv_scores)
print("Average CV Score:", cv_scores.mean())

"""Save the Model"""

import joblib

joblib.dump(clf, 'breast_cancer_model.pkl')
joblib.dump(scaler, 'scaler.pkl')